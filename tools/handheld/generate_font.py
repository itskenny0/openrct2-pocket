"""Generate the renamed Pocket Sans coverage atlas from licensed DejaVu Sans."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path)
parser.add_argument("output", type=Path)
parser.add_argument("--namespace", default="PocketSans")
parser.add_argument("--width", type=int, default=12)
parser.add_argument("--size", type=int, default=12)
parser.add_argument("--height", type=int, default=16)
args = parser.parse_args()
font = ImageFont.truetype(str(args.font), args.size)
lines = ["// Generated by tools/handheld/generate_font.py. See PocketSans.LICENSE.",
         "#pragma once", "#include <array>", "#include <cstdint>",
         f"namespace OpenRCT2::Ui::Handheld::{args.namespace} {{",
         f"inline constexpr int kWidth = {args.width}, kHeight = {args.height};",
         "inline constexpr std::array<uint8_t, 95> kAdvance = {"]
lines.append(",".join(str(round(font.getlength(chr(code)))) for code in range(32, 127)))
lines += ["};", "inline constexpr std::array<const char*, 95> kCoverage = {"]
for code in range(32, 127):
    image = Image.new("L", (args.width, args.height))
    ImageDraw.Draw(image).text((0, args.size), chr(code), font=font, fill=255, anchor="ls")
    lines.append('"' + ''.join(format(round(value / 17), 'x') for value in image.tobytes()) + '",')
lines += ["};", "}"]
args.output.write_text('\n'.join(lines) + '\n')
