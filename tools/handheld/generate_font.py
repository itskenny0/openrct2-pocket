"""Generate the renamed Pocket Sans coverage atlas from licensed DejaVu Sans."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
font = ImageFont.truetype(str(args.font), 12)
lines = ["// Generated by tools/handheld/generate_font.py. See PocketSans.LICENSE.",
         "#pragma once", "#include <array>", "#include <cstdint>",
         "namespace OpenRCT2::Ui::Handheld::PocketSans {",
         "inline constexpr int kWidth = 12, kHeight = 16;",
         "inline constexpr std::array<uint8_t, 95> kAdvance = {"]
lines.append(",".join(str(round(font.getlength(chr(code)))) for code in range(32, 127)))
lines += ["};", "inline constexpr std::array<const char*, 95> kCoverage = {"]
for code in range(32, 127):
    image = Image.new("L", (12, 16))
    ImageDraw.Draw(image).text((0, 12), chr(code), font=font, fill=255, anchor="ls")
    lines.append('"' + ''.join(format(round(value / 17), 'x') for value in image.tobytes()) + '",')
lines += ["};", "}"]
args.output.write_text('\n'.join(lines) + '\n')
